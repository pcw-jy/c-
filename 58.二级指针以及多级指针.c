////二、二级指针（重点）
////
////1. 定义
////
////指向一级指针的指针，用来存放一级指针变量的地址。
////语法： 数据类型 * *指针名;
////
////2. 内存关系
//
////
//int a = 10;
//int* p = &a;   // 一级指针 p → 存 a 的地址
//int** pp = &p; // 二级指针 pp → 存 p 的地址
//
//
////层级关系： pp → p → a 
////
////3. 取值 / 解引用规则
////
////- pp ：二级指针自身的值，即一级指针  p  的地址
////- *pp ：对二级指针解引用，得到一级指针 p 的值（也就是变量  a  的地址）
////- **pp ：两次解引用，最终得到变量 a 的值
////
////示例代码：
////
////
//#include <stdio.h>
//int main() {
//    int a = 10;
//    int* p = &a;
//    int** pp = &p;
//
//    printf("a = %d\n", a);
//    printf("*p = %d\n", *p);
//    printf("**pp = %d\n", **pp);
//
//    **pp = 99;  // 通过二级指针修改 a
//    printf("a = %d\n", a);
//    return 0;
//}
//
//
////4. 常见用途
////
////1. 修改一级指针本身的值
////普通函数传一级指针，只能修改指向的变量；传二级指针，可以修改实参一级指针的指向//
//void change(int** pp) {
//    int b = 20;
//    *pp = &b; // 修改原一级指针 p 的指向
//}
//int main() {
//    int a = 10;
//    int* p = &a;
//    change(&p);
//    printf("%d", *p); // 输出 20
//    return 0;
//}
//
////2. 操作字符串数组 / 二维字符数组（高频考点）
////字符串数组  char* str[]  本质就是二级指针。c//
//char* str[] = { "abc", "def", "ghi" };
//char** p = str;
//// *p 取每行字符串首地址，**p 取第一个字符
//printf("%s", *p);   // abc
//
////3. 动态内存分配中开辟二维数组。
////
////
////
////三、多级指针（三级及以上）
////
////1. 定义规则
////
////遵循几重指针就加几个 * ：
////
////- 一级指针： int * p;
////-二级指针： int * *pp;
////-三级指针： int * **ppp;
////-n 级指针：对应 n 个 *
////
////2. 解引用逻辑（通用规律）
////
////n 级指针  → n 次解引用才能访问到最终普通变量。
////
////示例（三级指针）：
//
////
//int a = 10;
//int* p = &a;
//int** pp = &p;
//int*** ppp = &pp;
//
//// 取值
//***ppp = 100; // 最终修改 a
//
//
////3. 使用原则
////
////- 工程中极少使用三级及以上指针，可读性极差、极易出错。
////- 日常开发、C 语言二级考试：掌握到二级指针即可。
//
//
//
//
////四、易混考点 & 易错点
////
////1. 取地址 & 和解引用 * 互逆
////& *p  = p ，  * &a  = a 
////2. 类型匹配（最常报错） - int* 只能接收 & int变量 
////- int** 只能接收 & int* 变量 
////错误示例：
//
////
//int a;
//int** pp = &a; // 报错！类型不匹配
//
////3. 指针不能越界解引用，野指针（指向未知内存）严禁 * 操作。
////4. 数组名本质是首元素地址，字符指针数组天然适配二级指针。
//
//
